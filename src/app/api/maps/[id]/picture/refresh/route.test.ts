import { isolatePictureData } from "@/lib/test-support/picture-data";
import { afterAll, expect, it, vi } from "vitest";
const runtime = vi.hoisted(() => ({ service: undefined as unknown }));
vi.mock("@/lib/pictures/start", () => ({ activePictureService: () => runtime.service }));
import { POST } from "./route";
import { PictureService } from "@/lib/pictures/service";
import { createMap, mapsOverview } from "@/lib/map-service";
import { testAccountScope, testAccountRequest } from "@/lib/test-support/accounts";
import { closeMetadataDb, metadataDb } from "@/lib/metadata/db";
import { documentFacts } from "@/lib/metadata/document-facts";
import { getPictureState } from "@/lib/pictures/state";
import { pictureTarget, publishPicture } from "@/lib/pictures/publication";
import { NO_INPUTS } from "@/lib/query/evaluation-inputs";
isolatePictureData(); afterAll(closeMetadataDb);
it("owner and Editor coalesce, Viewer refuses, unavailable is explicit, and versions follow publication", async () => {
  const scope = testAccountScope(), editor = testAccountScope(undefined, "editor"), viewer = testAccountScope(undefined, "viewer");
  const map = createMap(scope, "Refresh"), db = metadataDb();
  db.prepare("INSERT INTO projects(id,name,owner_id,created_at,updated_at) VALUES('project','Project',?,'time','time')").run(scope.accountId);
  db.prepare("UPDATE maps SET project_id='project' WHERE id=?").run(map.id);
  db.prepare("INSERT INTO project_people VALUES('project',?,'editor','time')").run(editor.accountId);
  db.prepare("INSERT INTO project_people VALUES('project',?,'viewer','time')").run(viewer.accountId);
  let available = true;
  runtime.service = new PictureService({ baseUrl: "http://fixture.test", available: () => available, run: async () => {} });
  const post = (id: string) => POST(testAccountRequest(new Request(`http://fixture.test/api/maps/${map.id}/picture/refresh`, { method: "POST" }), db, id), { params: Promise.resolve({ id: map.id }) });
  const facts = documentFacts({ kind: "map", id: map.id });
  expect((await post(scope.accountId)).status).toBe(202);
  const first = getPictureState(map.id)!;
  expect((await post(editor.accountId)).status).toBe(202);
  expect(getPictureState(map.id)?.requestedGeneration).toBe(first.requestedGeneration);
  expect((await post(viewer.accountId)).status).toBe(403);
  let listed = (await mapsOverview(scope)).find(row => row.id === map.id)!;
  expect(listed).toMatchObject({ hasThumbnail: false, pictureState: "waiting", pictureVersion: null });
  await publishPicture(scope, pictureTarget(scope, map.id), first.requestedGeneration, { light: Buffer.from("light"), dark: Buffer.from("dark") }, NO_INPUTS);
  listed = (await mapsOverview(scope)).find(row => row.id === map.id)!;
  expect(listed).toMatchObject({ hasThumbnail: true, pictureState: "current" }); expect(listed.pictureVersion).toBeTypeOf("string");
  available = false;
  expect(await (await post(editor.accountId)).json()).toMatchObject({ outcome: "unavailable", pictureState: "unavailable" });
  expect((await mapsOverview(scope)).find(row => row.id === map.id)?.pictureVersion).toBe(listed.pictureVersion);
  expect(documentFacts({ kind: "map", id: map.id })).toEqual(facts);
});
