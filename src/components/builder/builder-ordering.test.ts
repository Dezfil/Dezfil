import { afterEach, expect, it, vi } from "vitest";
import { hookReact, HookHarness } from "../workflow-canvas/hook-harness";
import { wire } from "../workflow-canvas/fetch-wire";
import type { Layer, MapWithLayers } from "@/lib/metadata/maps";
vi.mock("react", () => hookReact);
import { useBuilderMutations } from "./use-builder-mutations";
import { useBuilderCamera } from "./use-builder-camera";

afterEach(() => vi.unstubAllGlobals());
it("keeps queued opacity through the preceding map save and accepted opacity through a late camera echo", async () => {
  const w = wire();
  vi.stubGlobal("fetch", w.fetch);
  vi.stubGlobal("window", { addEventListener() {}, removeEventListener() {} });
  const layer = { id: "a", sql: "SELECT 1", style: { opacity: 1 } } as unknown as Layer;
  const initial = { id: "map", name: "Map", layers: [layer], widgets: [], editRevision: "initial" } as unknown as MapWithLayers;
  let map = initial;
  const shown: number[] = [];
  const h = new HookHarness(() => {
    const editor = useBuilderMutations({ mapId: "map", map, setMap: next => {
      map = typeof next === "function" ? next(map)! : next!;
      shown.push(map.layers[0].style.opacity);
    }, rendersRef: { current: {} }, setRenders() {}, setSelectedId() {}, refreshLayer: async () => {} });
    const camera = useBuilderCamera("map", { current: null }, editor.track);
    return { editor, camera };
  });
  try {
    const { editor, camera } = h.value;
    editor.serverMapRef.current = initial;
    editor.authoritativeLayersRef.current = { a: layer };
    editor.sequence.accept(initial);
    const rename = editor.patchMap({ name: "Renamed" });
    const opacity = editor.patchLayer("a", { style: { opacity: 0.5 } });
    const queuedAt = shown.length - 1;
    await w.settle();
    expect(map.layers[0].style.opacity).toBe(0.5);
    expect(editor.serverMapRef.current.layers[0].style.opacity).toBe(1);
    expect(w.calls.map(call => call.path)).toEqual(["/api/maps/map"]);
    w.calls[0].ok({ ...initial, name: "Renamed", editRevision: "renamed" });
    await rename; await w.settle();
    expect(map.layers[0].style.opacity).toBe(0.5);
    const write = w.pending("PATCH", "/api/layers/a")[0];
    expect(write.headers.get("X-Edit-Revision")).toBe("renamed");
    expect(write.body).toEqual({ style: { opacity: 0.5 } });
    camera({ lng: 1, lat: 2, zoom: 3 });
    const cameraWrite = w.pending("PATCH", "/api/maps/map")[0];
    expect(cameraWrite.headers.has("X-Edit-Revision")).toBe(false);
    write.ok({ ...layer, style: { opacity: 0.5 }, editRevision: "styled" });
    await opacity;
    expect(editor.serverMapRef.current.layers[0].style.opacity).toBe(0.5);
    // This full-map body was captured before the layer save was accepted.
    cameraWrite.ok({ ...initial, editRevision: "renamed" });
    await w.settle();
    expect(editor.sequence.revision).toBe("styled");
    expect(editor.serverMapRef.current.layers[0].style.opacity).toBe(0.5);
    expect(map.layers[0].style.opacity).toBe(0.5);
    expect(shown.slice(queuedAt)).toEqual(shown.slice(queuedAt).map(() => 0.5));
  } finally { h.unmount(); }
});

it("orders real layer, map and history hooks with accepted field intent and independent camera", async () => {
  const w = wire();
  vi.stubGlobal("fetch", w.fetch);
  vi.stubGlobal("window", { addEventListener() {}, removeEventListener() {} });
  const first = { id: "a", sql: "old", style: { opacity: 1, fill: "red" } } as unknown as Layer;
  const second = { ...first, id: "b" };
  let map = { id: "map", layers: [first, second], widgets: [], editRevision: "initial" } as unknown as MapWithLayers;
  const rendersRef = { current: {} };
  const harness = new HookHarness(() => {
    const mutations = useBuilderMutations({ mapId: "map", map, setMap: (next) => { map = typeof next === "function" ? next(map) as MapWithLayers : next!; }, rendersRef, setRenders() {}, setSelectedId() {}, refreshLayer: async () => {} });
    const camera = useBuilderCamera("map", { current: null }, mutations.track);
    return { ...mutations, camera };
  });
  const editor = harness.value;
  editor.serverMapRef.current = map;
  editor.authoritativeLayersRef.current = { a: first, b: second };
  editor.sequence.accept({ editRevision: "initial" });
  const sql = editor.patchLayer("a", { sql: "slow" });
  const fill = editor.patchLayer("b", { style: { opacity: 1, fill: "blue" } });
  const opacity = editor.patchLayer("b", { style: { opacity: 0.5, fill: "red" } });
  const settings = editor.patchMap({ name: "new" });
  editor.camera({ lng: 1, lat: 2, zoom: 3 });
  await w.settle();
  expect(w.calls.map((c) => c.path)).toEqual(["/api/layers/a", "/api/maps/map"]);
  expect(w.calls[1].headers.has("X-Edit-Revision")).toBe(false);
  expect(w.calls[0].headers.get("X-Edit-Revision")).toBe("initial");
  w.calls[1].ok({ editRevision: "camera-must-not-win" });
  const facts = { lastChangedAt: "2026-10-02", lastChangedBy: { name: "Ada", sqlName: "ada" } };
  w.calls[0].ok({ ...first, sql: "slow", editRevision: "sql", ...facts });
  await sql; await w.settle();
  expect(map).toMatchObject(facts);
  expect(w.calls[2].headers.get("X-Edit-Revision")).toBe("sql");
  expect(w.calls[2].body).toEqual({ style: { opacity: 1, fill: "blue" } });
  w.calls[2].ok({ ...second, style: { opacity: 1, fill: "blue" }, editRevision: "fill" });
  await fill; await w.settle();
  expect(w.calls[3].headers.get("X-Edit-Revision")).toBe("fill");
  expect(w.calls[3].body).toEqual({ style: { opacity: 0.5, fill: "blue" } });
  w.calls[3].ok({ ...second, style: { opacity: 0.5, fill: "blue" }, editRevision: "opacity" });
  await opacity; await w.settle();
  expect(w.calls[4].body).toEqual({ name: "new" });
  w.calls[4].ok({ ...editor.serverMapRef.current, name: "new", editRevision: "map-save" });
  await settings; await w.settle();
  editor.setHistory({ canUndo: true, canRedo: false, editRevision: "map-save", undoTarget: { eligible: true, reason: null, steps: [] } });
  const history = editor.applyHistory("undo");
  await w.settle();
  expect(w.calls[5].path).toBe("/api/maps/map/undo");
  w.calls[5].ok({ ...map, layers: [], history: { canUndo: false, canRedo: true }, editRevision: "undo" });
  await history;
  expect(editor.sequence.revision).toBe("undo");
  let settleTurn!: () => void;
  const assistant = editor.turn(() => new Promise<void>((resolve) => { settleTurn = resolve; }));
  const later = editor.patchMap({ name: "after assistant" });
  await w.settle();
  expect(w.calls).toHaveLength(6);
  settleTurn();
  await w.settle();
  expect(w.calls[6].method).toBe("GET");
  w.calls[6].ok({ ...map, layers: [], editRevision: "assistant-result" });
  await assistant; await w.settle();
  expect(w.calls[7].headers.get("X-Edit-Revision")).toBe("assistant-result");
  w.calls[7].ok({ ...map, layers: [], name: "after assistant", editRevision: "later" });
  await later;
  harness.unmount();
});
