import { afterEach, expect, it, vi } from "vitest";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { performance } from "node:perf_hooks";
import { HookHarness, hookReact } from "../workflow-canvas/hook-harness";
import { wire } from "../workflow-canvas/fetch-wire";
import type { MapWithLayers } from "@/lib/metadata/maps";
vi.mock("react", () => hookReact);
import { useBuilderMutations } from "./use-builder-mutations";
afterEach(() => vi.unstubAllGlobals());

it("keeps an assistant restyle between overlapping slider intents and measures queue wait separately", async () => {
  const w = wire(); vi.stubGlobal("fetch", w.fetch);
  vi.stubGlobal("window", { addEventListener() {}, removeEventListener() {} });
  const layer = { id: "l", sql: "select 1", style: { opacity: 1, fill: "red" } };
  let map = { id: "m", layers: [layer], widgets: [], editRevision: "initial" } as unknown as MapWithLayers;
  const harness = new HookHarness(() => useBuilderMutations({ mapId: "m", map, setMap: next => { map = typeof next === "function" ? next(map)! : next!; }, rendersRef: { current: {} }, replaceRenders: async () => null, setSelectedId() {}, refreshLayer: async () => {} }));
  const editor = harness.value; editor.serverMapRef.current = map; editor.sequence.accept(map);
  editor.authoritativeLayersRef.current = { l: map.layers[0] };
  const first = editor.patchLayer("l", { sql: "select 2" });
  const sqlStarted = performance.now();
  let assistantStarted = 0;
  const turn = editor.turn(async () => { assistantStarted = performance.now(); await fetch("/assistant-restyle", { method: "POST" }); });
  const queuedAt = performance.now();
  const slider = editor.patchLayer("l", { style: { opacity: 0.4, fill: "red" } });
  await w.settle();
  expect(w.calls.map(c => c.path)).toEqual(["/api/layers/l"]);
  expect(map.layers[0].style.opacity).toBe(0.4);
  // The controlled SQL response includes real elapsed latency; no engine timing is inferred.
  await new Promise(resolve => setTimeout(resolve, 60));
  const sqlFinished = performance.now();
  w.calls[0].ok({ ...layer, sql: "select 2", editRevision: "sql" });
  await first; await w.settle();
  expect(w.calls[1].path).toBe("/assistant-restyle");
  w.calls[1].ok({}); await w.settle();
  expect(w.calls[2].method).toBe("GET");
  w.calls[2].ok({ ...map, layers: [{ ...layer, sql: "select 2", style: { opacity: 1, fill: "blue" } }], editRevision: "assistant" });
  await turn; await w.settle();
  const sliderStarted = performance.now();
  expect(w.calls[3].headers.get("X-Edit-Revision")).toBe("assistant");
  expect(w.calls[3].body).toEqual({ style: { opacity: 0.4, fill: "blue" } });
  w.calls[3].ok({ ...layer, style: { opacity: 0.4, fill: "blue" }, editRevision: "slider" });
  await slider;
  expect(editor.sequence.stale).toBe(false);
  expect(map.layers[0].style).toMatchObject({ opacity: 0.4, fill: "blue" });
  expect(assistantStarted).toBeGreaterThanOrEqual(sqlFinished);
  expect(sliderStarted - queuedAt).toBeGreaterThanOrEqual(sqlFinished - queuedAt);
  const measurement = JSON.stringify({ injectedSqlResponseMs: +(sqlFinished - sqlStarted).toFixed(2), assistantQueueWaitMs: +(assistantStarted - sqlStarted).toFixed(2), sliderQueueWaitMs: +(sliderStarted - queuedAt).toFixed(2) });
  if (process.env.DEZFIL_DATA_DIR) writeFileSync(join(process.env.DEZFIL_DATA_DIR, "ordering-delay.json"), measurement);
  harness.unmount();
});
