it("pairs reached maps, lists, children and publication with safe covered-change facts", async () => {
  const scope = testAccountScope(db), map = createMap(scope, "Map");
  const layer = await createLayer(scope, map.id, { name: "Layer", sql: "SELECT ST_Point(1,2) AS geom" }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  publishMap(scope, map.id, {}, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  const facts = readDocumentRevision({ kind: "map", id: map.id }, db)!;
  const expected = { editRevision: facts.editRevision, lastChangedAt: facts.lastChangedAt,
    lastChangedBy: { name: scope.accountId, sqlName: "test_account" } };
  expect(readMap(scope, map.id)).toMatchObject(expected);
  expect(mapsOverview(scope)[0]).toMatchObject(expected);
  const response = await getLayer(testAccountRequest(new Request(`http://instance.test/api/layers/${layer.id}`), db), { params: Promise.resolve({ id: layer.id }) });
  expect(await response.json()).toMatchObject(expected);
  expect(getPublicationState(scope, map.id)).toMatchObject(expected);
  const token = publishMap(scope, map.id, {}, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision }).token;
  const anonymous = JSON.stringify(getPublishedSnapshot(token));
  expect(anonymous).not.toMatch(/editRevision|lastChanged|executableRevision|test_account|example.test/);
  updateMap(scope, map.id, { viewport: { lng: 2, lat: 3, zoom: 4 } }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  expect(readMap(scope, map.id)).toMatchObject(expected);
});
it("holds a workflow's revision with its captured steps across asynchronous presentation", async () => {
  const scope = testAccountScope(db), recipe = createRecipe(scope, "Workflow", db);
  const step = addStep(scope, recipe.id, { operation: "sql_step", parameters: { sql: "SELECT 1", name: "out" } }, db, { expectedRevision: readEditRevision({ kind: "workflow", id: recipe.id }, db)?.editRevision });
  const before = readDocumentRevision({ kind: "workflow", id: recipe.id }, db)!;
  let release!: () => void, entered!: () => void;
  const waiting = new Promise<void>(resolve => { entered = resolve; });
  const barrier = new Promise<void>(resolve => { release = resolve; });
  vi.spyOn(reads, "stepReads").mockImplementation(async () => { entered(); await barrier; return []; });
  const pending = readRecipe(scope, recipe.id);
  await waiting;
  editStep(scope, step.id, { sql: "SELECT 2", name: "out" }, db, undefined, { expectedRevision: readEditRevision({ kind: "workflow", id: (readEditStep(step.id, db)?.recipeId ?? "missing") }, db)?.editRevision });
  release();
  const result = recipePayload(await pending);
  expect(result).toMatchObject({ editRevision: before.editRevision, steps: [{ parameters: { sql: "SELECT 1" }, editRevision: before.editRevision }] });
  const current = readDocumentRevision({ kind: "workflow", id: recipe.id }, db)!;
  expect(current.editRevision).not.toBe(before.editRevision);
  expect(layoutPayload(readLayout(scope, recipe.id, db))).toMatchObject({ editRevision: current.editRevision });
});
it("preserves unknown authors and names a departed actor without account-management details", () => {
  const scope = testAccountScope(db), map = createMap(scope, "Map");
  db.prepare("UPDATE maps SET last_changed_by = NULL WHERE id = ?").run(map.id);
  expect(readMap(scope, map.id)).toMatchObject({ lastChangedBy: null });
  const departed = testAccountScope(db, "departed");
  db.prepare("UPDATE maps SET last_changed_by = ? WHERE id = ?").run(departed.accountId, map.id);
  db.exec("UPDATE accounts SET status = 'deactivated' WHERE id = 'departed'");
  expect(readMap(scope, map.id)).toMatchObject({ lastChangedBy: { name: "departed", sqlName: "departed" } });
  expect(JSON.stringify(readMap(scope, map.id))).not.toMatch(/email|password|session|isAdmin|deactivated/);
});
it("pairs project entries and filing producers with each document's own revision", async () => {
  const scope = testAccountScope(db), map = createMap(scope, "Map");
  const { createProject } = await import("./metadata/owned-projects");
  const { projectMembers } = await import("./project-service");
  const { currentProducers, readMapDependencies } = await import("./map-dependencies");
  const { readWorkflowDependencies } = await import("./recipe-dependencies");
  const { recordOutput } = await import("./metadata/recipes");
  const recipe = createRecipe(scope, "Workflow", db);
  const step = addStep(scope, recipe.id, { operation: "sql_step", parameters: { sql: "SELECT 1", name: "out" } }, db, { expectedRevision: readEditRevision({ kind: "workflow", id: recipe.id }, db)?.editRevision });
  recordOutput(step.id, { id: "output", name: "out" }, "time", db);
  const project = createProject(scope, { name: "Project", members: { ...{ addMaps: [map.id], addRecipes: [recipe.id] }, expectedRevisions: readFilingRevisions({ addMaps: [map.id], addRecipes: [recipe.id] }, db) } }, db);
  const mapRevision = readDocumentRevision({ kind: "map", id: map.id }, db)!.editRevision;
  const workflowRevision = readDocumentRevision({ kind: "workflow", id: recipe.id }, db)!.editRevision;
  const members = await projectMembers(scope, project.id);
  expect(members.maps[0]).toMatchObject({ editRevision: mapRevision });
  expect(members.recipes[0]).toMatchObject({ editRevision: workflowRevision });
  expect(currentProducers(scope).get("output")).toMatchObject({ editRevision: workflowRevision });
  expect(await readMapDependencies(scope, map.id)).toMatchObject({ editRevision: mapRevision, datasets: [] });
  expect(await readWorkflowDependencies(scope, recipe.id)).toMatchObject({ editRevision: workflowRevision, datasets: [] });
});
it.each(["step", "workflow"])("keeps a reached workflow readable when a %s disappears during presentation", async removed => {
  const scope = testAccountScope(db), recipe = createRecipe(scope, "Workflow", db);
  const step = addStep(scope, recipe.id, { operation: "sql_step", parameters: { sql: "SELECT 1", name: "out" } }, db, { expectedRevision: readEditRevision({ kind: "workflow", id: recipe.id }, db)?.editRevision });
  const before = readDocumentRevision({ kind: "workflow", id: recipe.id }, db)!;
  let release!: () => void, entered!: () => void;
  const waiting = new Promise<void>(resolve => { entered = resolve; });
  const barrier = new Promise<void>(resolve => { release = resolve; });
  vi.spyOn(reads, "stepReads").mockImplementation(async () => { entered(); await barrier; return []; });
  const { GET } = await import("@/app/api/recipes/[id]/route");
  const get = () => GET(testAccountRequest(new Request(`http://instance.test/api/recipes/${recipe.id}`), db), { params: Promise.resolve({ id: recipe.id }) });
  const pending = get();
  await waiting;
  const { removeStep, deleteRecipe } = await import("./metadata/owned-recipes");
  if (removed === "step") removeStep(scope, step.id, db, { expectedRevision: before.editRevision });
  else deleteRecipe(scope, recipe.id, db, { expectedRevision: before.editRevision });
  release();
  const response = await pending;
  expect(response.status).toBe(removed === "step" ? 200 : 404);
  if (removed === "step") {
    expect(await response.json()).toMatchObject({ editRevision: before.editRevision, recipe: { editRevision: before.editRevision, steps: [{ id: step.id, editRevision: before.editRevision }] } });
    const current = readDocumentRevision({ kind: "workflow", id: recipe.id }, db)!;
    expect(await (await get()).json()).toMatchObject({ editRevision: current.editRevision, recipe: { editRevision: current.editRevision, steps: [] } });
    expect(current.editRevision).not.toBe(before.editRevision);
  }
});
