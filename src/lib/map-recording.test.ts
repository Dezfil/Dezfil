import { readDocumentRevision as readEditRevision } from "@/lib/metadata/revisions";
import { getLayer as readEditLayer } from "@/lib/metadata/maps";
import { removeLayer } from "./layer-removal";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { mkdtempSync, rmSync } from "node:fs";
import path from "node:path";
import { closeMetadataDb, metadataDb } from "./metadata/db";
import { testAccountScope } from "./test-support/accounts";
import { readDocumentRevision } from "./metadata/revisions";
import { createMap, duplicateMap, updateMap } from "./map-service";
import { createLayer, duplicateLayer, updateLayer } from "./layer-service";
import { publishMap, unpublishMap } from "./publish/publication-state";
import { saveThumbnail } from "./map-thumbnails";
import { createSketch, appendFeature, cascadeDeleteSketch } from "./sketch/store";
import { historyAvailability } from "./metadata/history";
import { retirementsSettled } from "./ingest/retire";

let directory: string;
const scratch = process.env.DEZFIL_DATA_DIR!;
beforeEach(() => {
  directory = mkdtempSync(path.join(scratch, "map-recording-"));
  process.env.DEZFIL_DATA_DIR = directory;
  closeMetadataDb();
});
afterEach(async () => {
  vi.restoreAllMocks();
  await retirementsSettled();
  closeMetadataDb();
  process.env.DEZFIL_DATA_DIR = scratch;
  rmSync(directory, { recursive: true, force: true });
});
const revision = (id: string) => readDocumentRevision({ kind: "map", id })!;
const sql = "SELECT ST_Point(1, 2) AS geom";
it("attributes creation and copying to the acting account", () => {
  const scope = testAccountScope();
  const map = createMap(scope, "First");
  expect(revision(map.id)).toMatchObject({ editRevision: expect.stringMatching(/^[a-f0-9]{32}$/), lastChangedBy: scope.accountId });
  const copy = duplicateMap(scope, map.id);
  expect(revision(copy.id).editRevision).not.toBe(revision(map.id).editRevision);
  expect(revision(copy.id).lastChangedBy).toBe(scope.accountId);
});
it("records same-clock edits and widget changes, excluding camera and no-ops", () => {
  const scope = testAccountScope();
  const map = createMap(scope, "First");
  vi.spyOn(Date, "now").mockReturnValue(1234567890000);
  const initial = revision(map.id);
  updateMap(scope, map.id, { name: "Second" }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  const changed = revision(map.id);
  expect(changed.editRevision).not.toBe(initial.editRevision);
  expect(changed.lastChangedAt).toBe(new Date(Date.now()).toISOString());
  updateMap(scope, map.id, { widgetsPublished: false, viewport: { lng: 2, lat: 3, zoom: 4 } }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(changed.editRevision);
  const stable = revision(map.id), history = historyAvailability(map.id);
  updateMap(scope, map.id, { name: "Second", widgetsPublished: false }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  updateMap(scope, map.id, { viewport: { lng: 5, lat: 6, zoom: 7 } }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  expect(revision(map.id)).toEqual(stable);
  expect(historyAvailability(map.id)).toEqual(history);
});
it("attributes an Editor's layer changes and records reorder and removal", async () => {
  const owner = testAccountScope(), editor = testAccountScope(undefined, "editor");
  const map = createMap(owner, "First");
  const db = metadataDb();
  db.prepare("INSERT INTO projects (id, name, owner_id, created_at, updated_at) VALUES ('p','P',?,'t','t')").run(owner.accountId);
  db.exec("INSERT INTO project_people VALUES ('p','editor','editor','t')");
  db.prepare("UPDATE maps SET project_id = 'p' WHERE id = ?").run(map.id);
  let previous = revision(map.id);
  const layer = await createLayer(editor, map.id, { name: "Layer", sql }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  expect(revision(map.id).lastChangedBy).toBe(editor.accountId);
  previous = revision(map.id);
  await updateLayer(editor, layer.id, { name: "Changed" }, { expectedRevision: readEditRevision({ kind: "map", id: (readEditLayer(layer.id)?.mapId ?? "missing") })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  await updateLayer(editor, layer.id, { name: "Changed" }, { expectedRevision: readEditRevision({ kind: "map", id: (readEditLayer(layer.id)?.mapId ?? "missing") })?.editRevision });
  expect(revision(map.id)).toEqual(previous);
  const copy = duplicateLayer(editor, layer.id, { expectedRevision: readEditRevision({ kind: "map", id: (readEditLayer(layer.id)?.mapId ?? "missing") })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  updateMap(editor, map.id, { layerOrder: [copy.id, layer.id] }, { expectedRevision: readEditRevision({ kind: "map", id: map.id })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  await removeLayer(editor, copy.id, { expectedRevision: readEditRevision({ kind: "map", id: (readEditLayer(copy.id)?.mapId ?? "missing") })?.editRevision });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
});
it("records publication changes once and leaves repeated settings alone", () => {
  const scope = testAccountScope(), map = createMap(scope, "First");
  let previous = revision(map.id);
  publishMap(scope, map.id);
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  publishMap(scope, map.id, { theme: "dark" });
  expect(revision(map.id)).toEqual(previous);
  publishMap(scope, map.id, { theme: "light", viewerControls: { tilt: false } });
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  unpublishMap(scope, map.id);
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  previous = revision(map.id);
  unpublishMap(scope, map.id);
  expect(revision(map.id)).toEqual(previous);
});
it("excludes thumbnail landing from revision, actor and history", async () => {
  const scope = testAccountScope(), map = createMap(scope, "First");
  const previous = revision(map.id), history = historyAvailability(map.id);
  await saveThumbnail(scope, map.id, Buffer.from("image"));
  expect(revision(map.id)).toEqual(previous);
  expect(historyAvailability(map.id)).toEqual(history);
});
it("records sketch attachment and removal but excludes feature contents", async () => {
  const scope = testAccountScope(), map = createMap(scope, "First");
  const point = { kind: "point", geometry: { type: "Point", coordinates: [1, 2] } };
  const previous = revision(map.id);
  const sketch = await createSketch(scope, map.id, point);
  expect(revision(map.id).editRevision).not.toBe(previous.editRevision);
  const attached = revision(map.id);
  await appendFeature(scope, sketch.table.name, point);
  expect(revision(map.id)).toEqual(attached);
  await cascadeDeleteSketch(scope, sketch.table.name, "layer", { expectedRevision: attached.editRevision });
  expect(revision(map.id).editRevision).not.toBe(attached.editRevision);
});
