/**
 * The faint boundary. The faint ink is decoration only: placeholders,
 * ornament glyphs and separators, the bare no-value mark, line and row
 * numbers. Interface text at rest is not faded by transparency either, by
 * its own opacity or a parent's, outside disabled controls and short
 * transient states.
 *
 * The source collector reads the whole tree (stylesheets, the elements the
 * components draw with the classes they can wear, styles set in code) and
 * the check holds four layers against one list:
 *
 *   - declarations: every text colour that resolves to the faint ink;
 *   - elements: every element that wears such a style, so a listed
 *     decoration style put on a new element is growth;
 *   - inheritance: text inside such an element that sets no ink of its own;
 *   - opacity: every fade under one at rest over an element with text in
 *     it, whatever that text's colour.
 *
 * ALLOWED (faint-boundary.allowed.json) holds the uses that stay, each with
 * a kind the use must still have: placeholder, ornament, no-value,
 * numbering, disabled, transient, non-text, and syntax for the code
 * editor's own token colours, which this boundary does not rule on. A row
 * that reaches no element says why in `unseen`; a non-text row whose text
 * takes another ink in the state it shows names that rule in `textInk`.
 *
 * The list is compared both ways: a use, element or inheriting text that no
 * row names fails as growth, and a row whose use, element or text is gone
 * fails as stale. `node scripts/faint-report.mjs [folder]` prints the uses
 * of a folder with their kinds, and what the check would fail on.
 */

type Row = {
  layer: "ink" | "opacity";
  id: string;
  kind?: string;
  unseen?: string;
  textInk?: string;
  elements?: string[];
  inherits?: string[];
  inside?: string[];
};
type Finding = { check: string; key: string; message: string };
type Use = { layer: string; id: string; origin: string; elements: Map<string, unknown>; inherits: Map<string, unknown>; inside: Map<string, unknown> };
type Uses = { uses: Map<string, Use>; context: unknown };

