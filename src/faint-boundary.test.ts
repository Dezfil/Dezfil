/** A seeded tree: `top` is written at the top of the component's module,
 * `head` in its body before it draws, and `files` adds files beside it. */
type Seed = { css?: string; body?: string; extra?: string; baseCss?: string; top?: string; head?: string; files?: Record<string, string> };
function tree({ css = "", body = BASE_BODY, extra = "", baseCss = BASE_CSS, top = "", head = "", files = {} }: Seed = {}): Map<string, string> {
  const tsx = `import styles from "./panel.module.css";${top}
export function Panel({ busy, dragging }: { busy: boolean; dragging: boolean }) {${head}
  return (
    <section>${body}${extra}
    </section>
  );
}
`;
  return new Map([
    [CSS, baseCss + css],
    [TSX, tsx],
    ...Object.entries(files),
  ]);
}
const usesOf = (sources: Map<string, string>): Uses => faintUses(collect({ root: "/fixture", sources }));

/** Rows for every use of a tree, as a list written for it would hold them. */
function rowsFor(uses: Uses, kinds: Record<string, string>): Row[] {
  return [...uses.uses.values()].map((u) => ({
    layer: u.layer as Row["layer"],
    id: u.id,
    kind: kinds[u.layer + " :: " + u.id],
    elements: [...u.elements.keys()],
    inherits: [...u.inherits.keys()],
    inside: [...u.inside.keys()],
  }));
}

const KIND_OF = {
  [`ink :: ${CSS} :: .sep`]: "ornament",
  [`ink :: ${CSS} :: .field::placeholder`]: "placeholder",
  [`opacity :: ${CSS} :: .btn:disabled`]: "disabled",
  [`opacity :: ${CSS} :: .list[data-dragging="true"] .item`]: "transient",
  [`ink :: ${CSS} :: .tool`]: "non-text",
};
const BASE = rowsFor(usesOf(tree()), KIND_OF);
