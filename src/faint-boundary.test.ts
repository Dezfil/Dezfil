import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: plain-JS modules shared with the report command, no declaration file on purpose.
import { collect, faintUses, judge, keyOf, KINDS } from "../scripts/faint-uses.mjs";

/**
 * The faint boundary. The faint ink is decoration only: placeholders,
 * ornament glyphs and separators, the bare no-value mark, line and row
 * numbers. Interface text at rest is not faded by transparency either, by
 * its own opacity or a parent's, outside disabled controls and short
 * transient states.
 *
 * The source collector reads the whole tree (stylesheets, the elements the
 * components draw with the classes they can wear, styles set in code) and
 * the check holds four layers against one list:
 *
 *   - declarations: every text colour that resolves to the faint ink;
 *   - elements: every element that wears such a style, so a listed
 *     decoration style put on a new element is growth;
 *   - inheritance: text inside such an element that sets no ink of its own;
 *   - opacity: every fade under one at rest over an element with text in
 *     it, whatever that text's colour.
 *
 * ALLOWED (faint-boundary.allowed.json) holds the uses that stay, each with
 * a kind the use must still have: placeholder, ornament, no-value,
 * numbering, disabled, transient, non-text, and syntax for the code
 * editor's own token colours, which this boundary does not rule on. A row
 * that reaches no element says why in `unseen`; a non-text row whose text
 * takes another ink in the state it shows names that rule in `textInk`.
 *
 * The list is compared both ways: a use, element or inheriting text that no
 * row names fails as growth, and a row whose use, element or text is gone
 * fails as stale. `node scripts/faint-report.mjs [folder]` prints the uses
 * of a folder with their kinds, and what the check would fail on.
 */

type Row = {
  layer: "ink" | "opacity";
  id: string;
  kind?: string;
  unseen?: string;
  textInk?: string;
  elements?: string[];
  inherits?: string[];
  inside?: string[];
};
type Finding = { check: string; key: string; message: string };
type Use = { layer: string; id: string; origin: string; elements: Map<string, unknown>; inherits: Map<string, unknown>; inside: Map<string, unknown> };
type Uses = { uses: Map<string, Use>; context: unknown };

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const read = (name: string): Row[] => JSON.parse(readFileSync(path.join(HERE, name), "utf8"));
const ALLOWED = read("faint-boundary.allowed.json");

/**
 * What the collector cannot read, by file, kind and source text: a class
 * or a style it cannot resolve to rules. Listed both ways, so a new
 * unreadable site fails until it is read or named here.
 */
const UNREAD = new Set([
  // The font loaders' variables: classes generated by the font loader, not stylesheet rules.
  "src/app/document.tsx :: class :: archivo.variable",
  "src/app/document.tsx :: class :: dmMono.variable",
  "src/app/document.tsx :: class :: gabarito.variable",
  "src/app/document.tsx :: class :: inter.variable",
  "src/app/document.tsx :: class :: plexMono.variable",
  // A source's logo class, picked from a table of sources at run time.
  "src/components/SourceNav.tsx :: class :: spec.logoClass",
  // A highlighted SQL token's class, from the highlighter at run time.
  "src/components/sql/SqlExcerpt.tsx :: class :: p.cls",
  // Slider fills and range handles: positions computed by a function, no colour or opacity.
  "src/components/builder/filters/RangeBrush.tsx :: style :: {seat(hi)}",
  "src/components/builder/filters/RangeBrush.tsx :: style :: {seat(lo)}",
  "src/components/builder/style-panel/ContinuousBrush.tsx :: style :: {sliderFill(shown.center, clampLo, clampHi) as CSSProperties}",
  "src/components/builder/style-panel/rows.tsx :: style :: {sliderFill(shown, min, max)}",
  "src/components/builder/style-panel/size-rows.tsx :: style :: {sliderFill(positionFor(shown, min, max), 0, TRACK_STEPS)}",
]);

const model = collect({ root: ROOT });
const found: Uses = faintUses(model);
const findings: Finding[] = judge(found, { allowed: ALLOWED });
const failing = (...checks: string[]) => findings.filter((f) => checks.includes(f.check)).map((f) => f.message);

describe("the faint boundary", () => {
  it("reads the tree (the check is not vacuous)", () => {
    expect(model.stats.stylesheets).toBeGreaterThan(150);
    expect(model.stats.elements).toBeGreaterThan(5000);
    // Floors near 85% of what the tree holds, so a collector that stops
    // reading part of it fails here before the lists can agree with it.
    const uses = [...found.uses.values()];
    expect(uses.filter((u) => u.layer === "ink").length).toBeGreaterThanOrEqual(95);
    expect(uses.filter((u) => u.layer === "opacity").length).toBeGreaterThanOrEqual(50);
    expect(uses.filter((u) => u.origin === "code" && u.layer === "ink").length).toBeGreaterThanOrEqual(3);
    expect(uses.filter((u) => u.inherits.size > 0).length).toBeGreaterThanOrEqual(1);
    expect(uses.filter((u) => u.inside.size > 0).length).toBeGreaterThanOrEqual(22);
    expect(ALLOWED.length).toBeGreaterThan(100);
  });

  it("every faint text colour is listed (declarations)", () => {
    expect(failing("declaration")).toEqual([]);
  });

  it("every element wearing a listed style is listed (elements)", () => {
    expect(failing("element")).toEqual([]);
  });

  it("all text that inherits a listed faint ink is listed (inheritance)", () => {
    expect(failing("inheritance")).toEqual([]);
  });

  it("every fade over text at rest is listed, with the text inside it (opacity)", () => {
    expect(failing("opacity")).toEqual([]);
  });

  it("each allowed use still has its kind", () => {
    expect(failing("kind")).toEqual([]);
  });

  it("no row outlives its use, and no use is listed twice", () => {
    expect(failing("list")).toEqual([]);
  });

  it("what the collector cannot read is named, both ways", () => {
    const sites = new Set<string>(model.unresolved.map((u: { file: string; kind: string; text: string }) => `${u.file} :: ${u.kind} :: ${u.text}`));
    expect([...sites].filter((s) => !UNREAD.has(s))).toEqual([]);
    expect([...UNREAD].filter((s) => !sites.has(s))).toEqual([]);
  });
});

/* ---- seeded trees ---- */

const CSS = "src/fixture/panel.module.css";
const TSX = "src/fixture/Panel.tsx";
const BASE_CSS = `
.sep { color: var(--fg-faint); }
.field::placeholder { color: var(--fg-faint); }
.btn:disabled { opacity: 0.5; }
.list[data-dragging="true"] .item { opacity: 0.6; }
.tool { color: var(--fg-faint); }
.name { color: var(--fg); }
`;
const BASE_BODY = `
      <input className={styles.field} placeholder="Search layers" />
      <p>Parcels <i className={styles.sep}>·</i> 12 rows</p>
      <button className={styles.btn} disabled={busy}>Save</button>
      <ul className={styles.list} data-dragging={dragging}>
        <li className={styles.item}>Roads</li>
      </ul>
      <button className={styles.tool} aria-label="Export"><svg /></button>`;

type Seed = { css?: string; body?: string; extra?: string; baseCss?: string };
function tree({ css = "", body = BASE_BODY, extra = "", baseCss = BASE_CSS }: Seed = {}): Map<string, string> {
  const tsx = `import styles from "./panel.module.css";
export function Panel({ busy, dragging }: { busy: boolean; dragging: boolean }) {
  return (
    <section>${body}${extra}
    </section>
  );
}
`;
  return new Map([
    [CSS, baseCss + css],
    [TSX, tsx],
  ]);
}
const usesOf = (sources: Map<string, string>): Uses => faintUses(collect({ root: "/fixture", sources }));

/** Rows for every use of a tree, as a list written for it would hold them. */
function rowsFor(uses: Uses, kinds: Record<string, string>): Row[] {
  return [...uses.uses.values()].map((u) => ({
    layer: u.layer as Row["layer"],
    id: u.id,
    kind: kinds[u.layer + " :: " + u.id],
    elements: [...u.elements.keys()],
    inherits: [...u.inherits.keys()],
    inside: [...u.inside.keys()],
  }));
}

const KIND_OF = {
  [`ink :: ${CSS} :: .sep`]: "ornament",
  [`ink :: ${CSS} :: .field::placeholder`]: "placeholder",
  [`opacity :: ${CSS} :: .btn:disabled`]: "disabled",
  [`opacity :: ${CSS} :: .list[data-dragging="true"] .item`]: "transient",
  [`ink :: ${CSS} :: .tool`]: "non-text",
};
const BASE = rowsFor(usesOf(tree()), KIND_OF);
const judged = (seed: Seed, lists: { allowed?: Row[] } = { allowed: BASE }): Finding[] => judge(usesOf(tree(seed)), lists);
const checks = (f: Finding[]) => [...new Set(f.map((x) => x.check))].sort();

describe("the faint boundary on seeded trees", () => {
  it("the seeded tree passes with its list", () => {
    expect(BASE.map((r) => keyOf(r)).sort()).toEqual(Object.keys(KIND_OF).sort());
    expect(judged({})).toEqual([]);
  });

  it("fails on a faint hint", () => {
    const f = judged({ css: ".hint { color: var(--fg-faint); }", extra: `\n      <p className={styles.hint}>Only the owner can publish.</p>` });
    expect(checks(f)).toEqual(["declaration"]);
    expect(f[0].message).toContain('<p.hint> "Only the owner can publish."');
  });

  it("fails on a faint kicker, through a property defined from a faint hex", () => {
    const f = judged({
      css: ".panel { --label-ink: #93a19c; }\n.kicker { text-transform: uppercase; color: var(--label-ink); }",
      extra: `\n      <h3 className={styles.kicker}>Layers</h3>`,
    });
    expect(checks(f)).toEqual(["declaration"]);
    expect(f[0].key).toBe(`ink :: ${CSS} :: .kicker`);
  });

  it("fails on text that inherits faint from a listed parent", () => {
    const f = judged({ body: BASE_BODY.replace("<svg /></button>", "<svg /><span>Export</span></button>") });
    expect(checks(f)).toEqual(["inheritance", "kind"]);
    expect(f.find((x) => x.check === "inheritance")?.message).toContain('<span> "Export" inherits it');
  });

  it("fails on a faint style set in code", () => {
    const f = judged({ extra: `\n      <p style={{ color: "var(--fg-faint)" }}>Drag a corner to resize.</p>` });
    expect(checks(f)).toEqual(["declaration"]);
    expect(f[0].message).toContain("set in code");
  });

  it("fails on a hint faded by its own opacity", () => {
    const f = judged({ css: ".note { color: var(--fg-muted); opacity: 0.7; }", extra: `\n      <p className={styles.note}>Shared with 3 people.</p>` });
    expect(checks(f)).toEqual(["opacity"]);
    expect(f[0].message).toContain('<p.note> "Shared with 3 people."');
  });

  it("fails on a parent's opacity over a child with its own colour", () => {
    const f = judged({ css: ".card { opacity: 0.8; }", extra: `\n      <div className={styles.card}><b className={styles.name}>Parcels</b></div>` });
    expect(checks(f)).toEqual(["opacity"]);
    expect(f[0].message).toContain('<b.name> "Parcels"');
  });

  it("fails on a hint that reuses a listed decoration style, with no new style and no change to the list", () => {
    const f = judged({ extra: `\n      <small className={styles.sep}>Updated daily</small>` });
    expect(checks(f)).toEqual(["element", "kind"]);
    expect(f.find((x) => x.check === "element")?.message).toContain('<small.sep> "Updated daily" wears it');
  });

  it("fails on a use listed under a kind it does not have", () => {
    const hint = { css: ".hint { color: var(--fg-faint); }", extra: `\n      <p className={styles.hint}>Only the owner can publish.</p>` };
    const listed = rowsFor(usesOf(tree(hint)), { ...KIND_OF, [`ink :: ${CSS} :: .hint`]: "placeholder" });
    const f = judged(hint, { allowed: listed });
    expect(checks(f)).toEqual(["kind"]);
  });

  it("fails on a listed use that no longer exists", () => {
    const f = judged({ baseCss: BASE_CSS.replace(".tool { color: var(--fg-faint); }", "") });
    expect(f.map((x) => x.message)).toEqual([`ink :: ${CSS} :: .tool: the allowed row outlives its use`]);
  });

  /* Inheritance through a rule that sets no ink at rest. The container is
   * listed as an icon's colour, as a list written before the text came in
   * would hold it: no text inherits it. */
  const TOOL = `<button className={styles.tool} aria-label="Export"><svg /></button>`;
  const asIcon = (seed: Seed) => rowsFor(usesOf(tree(seed)), KIND_OF).map((r) => ({ ...r, inherits: [] }));

  it("fails on a link whose rule says color: inherit, inside a faint container", () => {
    const seed = {
      css: ".link { color: inherit; }",
      body: BASE_BODY.replace(TOOL, `<div className={styles.tool}><svg /><a className={styles.link} href="/x">Read the guide</a></div>`),
    };
    const f = judged(seed, { allowed: asIcon(seed) });
    expect(checks(f)).toEqual(["inheritance", "kind"]);
    expect(f.find((x) => x.check === "inheritance")?.message).toContain('<a.link> "Read the guide" inherits it');
  });

  it("fails at rest on text whose only own ink is set under an attribute it carries some of the time", () => {
    const seed = {
      css: ".label[data-on] { color: var(--fg); }",
      body: BASE_BODY.replace(TOOL, `<button className={styles.tool} aria-label="Export"><svg /><span className={styles.label} data-on={busy || undefined}>Export</span></button>`),
    };
    const f = judged(seed, { allowed: asIcon(seed) });
    expect(checks(f)).toEqual(["inheritance", "kind"]);
    expect(f.find((x) => x.check === "inheritance")?.message).toContain('<span.label> "Export" inherits it');
  });

  /* A use listed under a kind its name suggests, where the text it reaches
   * says otherwise. */
  const NAMED: [string, string, string, string][] = [
    ["a sentence styled as the no-value mark", ".nullCell { color: var(--fg-faint); }", `<span className={styles.nullCell}>No value was recorded</span>`, "no-value"],
    ["a sentence styled as a placeholder", ".placeholderNote { color: var(--fg-faint); }", `<p className={styles.placeholderNote}>Nothing here yet. Add a layer to start.</p>`, "placeholder"],
    ["a hint that only takes the pointer away, listed as disabled", ".hint { color: var(--fg-faint); pointer-events: none; }", `<p className={styles.hint}>Only the owner can publish.</p>`, "disabled"],
  ];
  it.each(NAMED)("fails on %s", (_name, css, body, kind) => {
    const seed = { css, extra: `\n      ${body}` };
    const uses = usesOf(tree(seed));
    const added = [...uses.uses.keys()].filter((k) => !(k in KIND_OF));
    expect(added).toHaveLength(1);
    const f = judge(uses, { allowed: rowsFor(uses, { ...KIND_OF, [added[0]]: kind }) });
    expect(checks(f)).toEqual(["kind"]);
    expect(f[0].message).toContain(`not ${kind}: `);
  });

  const POSITIVES: [string, string, string, string][] = [
    ["a placeholder", ".field::placeholder { color: var(--fg-faint); }", `<input className={styles.field} placeholder="Search layers" />`, "placeholder"],
    ["an ornament", ".sep { color: var(--fg-faint); }", `<p>Parcels <i className={styles.sep}>·</i> 12 rows</p>`, "ornament"],
    ["a disabled control", ".btn:disabled { color: var(--fg-faint); opacity: 0.5; }", `<button className={styles.btn} disabled={busy}>Save</button>`, "disabled"],
    ["a transient state", '.list[data-dragging="true"] .item { opacity: 0.6; }', `<ul className={styles.list} data-dragging={dragging}><li className={styles.item}>Roads</li></ul>`, "transient"],
  ];
  it.each(POSITIVES)("passes %s listed with its kind", (_name, css, body, kind) => {
    const seed = { baseCss: "", css, body: `\n      ${body}` };
    const uses = usesOf(tree(seed));
    expect(uses.uses.size).toBeGreaterThan(0);
    const listed = rowsFor(uses, Object.fromEntries([...uses.uses.keys()].map((k) => [k, kind])));
    expect(judge(uses, { allowed: listed })).toEqual([]);
    for (const row of listed) expect(KINDS[kind](uses.uses.get(keyOf(row)), row)).toBeNull();
  });
});
