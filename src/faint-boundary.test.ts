/** The sites a model cannot read, as `file :: kind :: text`. */
const sitesOf = (m: { unresolved: { file: string; kind: string; text: string }[] }): string[] => m.unresolved.map((u) => `${u.file} :: ${u.kind} :: ${u.text}`);
/** Sites no list entry names, and entries no site is left for, each
 * counted: a second element that wears the same unread style is a site of
 * its own, so the list names it twice. */
function unreadAgainst(sites: string[], named: string[]): { unnamed: string[]; stale: string[] } {
  const count = (list: string[]) => list.reduce((m, s) => m.set(s, (m.get(s) ?? 0) + 1), new Map<string, number>());
  const have = count(sites);
  const listed = count(named);
  const over = (a: Map<string, number>, b: Map<string, number>) => [...a].flatMap(([s, n]) => Array<string>(Math.max(0, n - (b.get(s) ?? 0))).fill(s));
  return { unnamed: over(have, listed), stale: over(listed, have) };
}

